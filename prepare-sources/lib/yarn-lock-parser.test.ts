import { describe, expect, it } from "vitest";
import {
  type Lockfile,
  type LockfileBlock,
  getMap,
  getNestedMap,
  getScalar,
  parseLockfile,
  serializeBlock,
  serializeLockfile,
} from "./yarn-lock-parser.ts";

function roundTrip(lockfile: Lockfile): string {
  return serializeLockfile(lockfile);
}

function expectFirstBlock(lockfile: Lockfile): LockfileBlock {
  const block = lockfile.blocks[0];
  expect(block).toBeDefined();
  if (!block) {
    throw new Error("expected block");
  }
  return block;
}

