describe("serializeBlock", () => {
  it("quotes all descriptors", () => {
    const block: LockfileBlock = {
      descriptors: ["pkg@npm:^1.0.0"],
      fields: { version: { kind: "scalar", raw: "1.0.0" } },
    };
    const output = serializeBlock(block);
    expect(output).toBe('"pkg@npm:^1.0.0":\n  version: 1.0.0');
  });

  it("serializes combined descriptors within one pair of quotes", () => {
    const block: LockfileBlock = {
      descriptors: ["pkg@npm:^1.0.0", "pkg@npm:^1.1.0"],
      fields: { version: { kind: "scalar", raw: "1.1.0" } },
    };
    const output = serializeBlock(block);
    expect(output.startsWith('"pkg@npm:^1.0.0, pkg@npm:^1.1.0":')).toBe(true);
  });
});

