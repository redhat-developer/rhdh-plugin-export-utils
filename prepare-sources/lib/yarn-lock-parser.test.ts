describe("parseLockfile", () => {
  it("captures the preamble including __metadata", () => {
    const input = [
      "# comment",
      "",
      "__metadata:",
      "  version: 8",
      "  cacheKey: 10c0",
      "",
      '"pkg@npm:^1.0.0":',
      "  version: 1.0.0",
      "",
    ].join("\n");

    const lockfile = parseLockfile(input);
    expect(lockfile.preamble).toBe("# comment\n\n__metadata:\n  version: 8\n  cacheKey: 10c0");
    expect(lockfile.blocks).toHaveLength(1);
  });

  it("handles lockfile without __metadata", () => {
    const input = ['"pkg@npm:^1.0.0":', "  version: 1.0.0", ""].join("\n");

    const lockfile = parseLockfile(input);
    expect(lockfile.preamble).toBe("");
    expect(lockfile.blocks).toHaveLength(1);
    const block = expectFirstBlock(lockfile);
    expect(block.fields.version).toEqual({
      kind: "scalar",
      raw: "1.0.0",
    });
  });

  it("parses combined descriptor keys", () => {
    const input = [
      "__metadata:",
      "  version: 8",
      "",
      '"@aws/types@npm:^3.0.0, @aws/types@npm:^3.1.0":',
      "  version: 3.1.0",
      "",
    ].join("\n");

    const lockfile = parseLockfile(input);
    const block = expectFirstBlock(lockfile);
    expect(block.descriptors).toEqual(["@aws/types@npm:^3.0.0", "@aws/types@npm:^3.1.0"]);
  });

  it("parses scalar, map, and nested-map fields", () => {
    const input = [
      "__metadata:",
      "  version: 8",
      "",
      '"@backstage/theme@backstage:^":',
      "  version: 0.6.3",
      '  resolution: "@backstage/theme@npm:0.6.3"',
      "  dependencies:",
      '    "@emotion/react": "npm:^11.0.0"',
      "  peerDependencies:",
      '    react: "npm:^18.0.0"',
      "  peerDependenciesMeta:",
      "    react:",
      "      optional: true",
      "  linkType: hard",
      "",
    ].join("\n");

    const lockfile = parseLockfile(input);
    const block = expectFirstBlock(lockfile);

    expect(block.fields.version).toEqual({ kind: "scalar", raw: "0.6.3" });
    expect(block.fields.resolution).toEqual({
      kind: "scalar",
      raw: '"@backstage/theme@npm:0.6.3"',
    });
    expect(block.fields.dependencies).toEqual({
      kind: "map",
      entries: { '"@emotion/react"': '"npm:^11.0.0"' },
    });
    expect(block.fields.peerDependencies).toEqual({
      kind: "map",
      entries: { react: '"npm:^18.0.0"' },
    });
    expect(block.fields.peerDependenciesMeta).toEqual({
      kind: "nested-map",
      entries: { react: { optional: "true" } },
    });
    expect(block.fields.linkType).toEqual({ kind: "scalar", raw: "hard" });
  });

  it("skips blank lines between blocks", () => {
    const input = [
      "__metadata:",
      "  version: 8",
      "",
      "",
      '"a@npm:1":',
      "  version: 1",
      "",
      "",
      "",
      '"b@npm:2":',
      "  version: 2",
      "",
    ].join("\n");

    const lockfile = parseLockfile(input);
    expect(lockfile.blocks).toHaveLength(2);
  });

  it("skips stray non-descriptor lines", () => {
    const input = [
      "__metadata:",
      "  version: 8",
      "",
      "this is a stray line without trailing colon",
      "",
      '"pkg@npm:1":',
      "  version: 1",
      "",
    ].join("\n");

    const lockfile = parseLockfile(input);
    expect(lockfile.blocks).toHaveLength(1);
    const block = expectFirstBlock(lockfile);
    expect(block.descriptors).toEqual(["pkg@npm:1"]);
  });

  it("handles unquoted descriptor (non-standard)", () => {
    const input = ["my-pkg@npm:1.0.0:", "  version: 1.0.0", ""].join("\n");

    const lockfile = parseLockfile(input);
    expect(lockfile.blocks).toHaveLength(1);
    const block = expectFirstBlock(lockfile);
    expect(block.descriptors).toEqual(["my-pkg@npm:1.0.0"]);
  });

  it("skips mid-file comment lines", () => {
    const input = [
      "__metadata:",
      "  version: 8",
      "",
      "# Inline comment between blocks",
      '"pkg@npm:1":',
      "  version: 1",
      "",
    ].join("\n");

    const lockfile = parseLockfile(input);
    expect(lockfile.blocks).toHaveLength(1);
  });

  it("handles nested-map with orphan property before key", () => {
    const input = [
      "__metadata:",
      "  version: 8",
      "",
      '"pkg@npm:1":',
      "  version: 1",
      "  peerDependenciesMeta:",
      "      orphan: true",
      "    react:",
      "      optional: true",
      "  linkType: hard",
      "",
    ].join("\n");

    const lockfile = parseLockfile(input);
    const block = expectFirstBlock(lockfile);
    expect(block.fields.peerDependenciesMeta).toEqual({
      kind: "nested-map",
      entries: { react: { optional: "true" } },
    });
    expect(block.fields.linkType).toEqual({ kind: "scalar", raw: "hard" });
  });
});

