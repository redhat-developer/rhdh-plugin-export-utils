describe("parser edge cases", () => {
  it("stops parsing block body on an empty line", () => {
    const input = ['"pkg@npm:1":', "  version: 1.0.0", "", "  linkType: hard", ""].join("\n");

    const lockfile = parseLockfile(input);
    expect(lockfile.blocks).toHaveLength(1);
    const block = expectFirstBlock(lockfile);
    expect(block.fields.version).toEqual({
      kind: "scalar",
      raw: "1.0.0",
    });
    expect(block.fields.linkType).toBeUndefined();
  });

  it("stops parsing block body on a 2-space line that is not a valid field", () => {
    const input = [
      '"pkg@npm:1":',
      "  version: 1.0.0",
      "  no-colon-here",
      "  linkType: hard",
      "",
    ].join("\n");

    const lockfile = parseLockfile(input);
    const block = expectFirstBlock(lockfile);
    expect(block.fields.version).toBeDefined();
    expect(block.fields.linkType).toBeUndefined();
  });

  it("handles a section header with no sub-content", () => {
    const input = [
      '"pkg@npm:1":',
      "  version: 1.0.0",
      "  dependencies:",
      "  linkType: hard",
      "",
    ].join("\n");

    const lockfile = parseLockfile(input);
    const block = expectFirstBlock(lockfile);
    expect(block.fields.dependencies).toBeUndefined();
    expect(block.fields.linkType).toEqual({ kind: "scalar", raw: "hard" });
  });

  it("skips malformed 4-space map entries", () => {
    const input = [
      '"pkg@npm:1":',
      "  version: 1.0.0",
      "  dependencies:",
      "    valid-dep: 1.0.0",
      "    no-colon-garbage",
      "  linkType: hard",
      "",
    ].join("\n");

    const lockfile = parseLockfile(input);
    const block = expectFirstBlock(lockfile);
    expect(block.fields.dependencies).toEqual({
      kind: "map",
      entries: { "valid-dep": "1.0.0" },
    });
  });

  it("skips malformed 6-space nested-map property lines", () => {
    const input = [
      '"pkg@npm:1":',
      "  peerDependenciesMeta:",
      "    react:",
      "      optional: true",
      "      garbage-no-colon",
      "  linkType: hard",
      "",
    ].join("\n");

    const lockfile = parseLockfile(input);
    const block = expectFirstBlock(lockfile);
    expect(block.fields.peerDependenciesMeta).toEqual({
      kind: "nested-map",
      entries: { react: { optional: "true" } },
    });
  });

  it("breaks nested-map on a 4-space line that is not a key header", () => {
    const input = [
      '"pkg@npm:1":',
      "  peerDependenciesMeta:",
      "    react:",
      "      optional: true",
      "    not-a-key-header 1.0.0",
      "  linkType: hard",
      "",
    ].join("\n");

    const lockfile = parseLockfile(input);
    const block = expectFirstBlock(lockfile);
    expect(block.fields.peerDependenciesMeta).toEqual({
      kind: "nested-map",
      entries: { react: { optional: "true" } },
    });
  });

  it("stops parsing on degenerate field lines with empty name", () => {
    const input = [
      '"pkg@npm:1":',
      "  version: 1.0.0",
      "  : orphan-value",
      "  :",
      "  linkType: hard",
      "",
    ].join("\n");

    const lockfile = parseLockfile(input);
    const block = expectFirstBlock(lockfile);
    expect(block.fields.version).toBeDefined();
    expect(block.fields[""]).toBeUndefined();
    expect(block.fields.linkType).toBeUndefined();
  });

  it("stops parsing on field lines with colon not followed by whitespace", () => {
    const input = [
      '"pkg@npm:1":',
      "  version: 1.0.0",
      "  name:value-no-space",
      "  linkType: hard",
      "",
    ].join("\n");

    const lockfile = parseLockfile(input);
    const block = expectFirstBlock(lockfile);
    expect(block.fields.version).toBeDefined();
    expect(block.fields.name).toBeUndefined();
    expect(block.fields.linkType).toBeUndefined();
  });

  it("handles map keys containing colons", () => {
    const input = [
      '"pkg@npm:1":',
      "  dependencies:",
      '    "key:with:colons": "npm:^1.0.0"',
      "    simple-key: value",
      "",
    ].join("\n");

    const lockfile = parseLockfile(input);
    const block = expectFirstBlock(lockfile);
    expect(block.fields.dependencies).toEqual({
      kind: "map",
      entries: {
        '"key:with:colons"': '"npm:^1.0.0"',
        "simple-key": "value",
      },
    });
  });

  it("handles nested-map keys containing colons", () => {
    const input = [
      '"pkg@npm:1":',
      "  peerDependenciesMeta:",
      "    key:sub:",
      "      optional: true",
      "",
    ].join("\n");

    const lockfile = parseLockfile(input);
    const block = expectFirstBlock(lockfile);
    expect(block.fields.peerDependenciesMeta).toEqual({
      kind: "nested-map",
      entries: { "key:sub": { optional: "true" } },
    });
  });

  it("handles nested-map property names containing colons", () => {
    const input = [
      '"pkg@npm:1":',
      "  peerDependenciesMeta:",
      "    react:",
      "      prop:name: true",
      "",
    ].join("\n");

    const lockfile = parseLockfile(input);
    const block = expectFirstBlock(lockfile);
    expect(block.fields.peerDependenciesMeta).toEqual({
      kind: "nested-map",
      entries: { react: { "prop:name": "true" } },
    });
  });

  it("drops orphan 4-space line that appears before any field header", () => {
    const input = ['"pkg@npm:1":', "    orphan-deep-line: value", "  version: 1.0.0", ""].join(
      "\n",
    );

    const lockfile = parseLockfile(input);
    const block = expectFirstBlock(lockfile);
    expect(block.fields.version).toEqual({ kind: "scalar", raw: "1.0.0" });
  });

  it("stops block parsing on stray non-indented line before first field", () => {
    const input = ['"pkg@npm:1":', "stray-line-at-top", "  version: 1.0.0", ""].join("\n");

    const lockfile = parseLockfile(input);
    const block = expectFirstBlock(lockfile);
    expect(block.fields.version).toBeUndefined();
  });

  it("stops block parsing on stray non-indented line inside a map section", () => {
    const input = [
      '"pkg@npm:1":',
      "  dependencies:",
      "    valid: 1.0.0",
      "stray-line",
      "  linkType: hard",
      "",
    ].join("\n");

    const lockfile = parseLockfile(input);
    const block = expectFirstBlock(lockfile);
    expect(block.fields.dependencies).toEqual({
      kind: "map",
      entries: { valid: "1.0.0" },
    });
    expect(block.fields.linkType).toBeUndefined();
  });

  it("stops block parsing on stray non-indented line inside a nested-map section", () => {
    const input = [
      '"pkg@npm:1":',
      "  peerDependenciesMeta:",
      "    react:",
      "      optional: true",
      "stray-line",
      "  linkType: hard",
      "",
    ].join("\n");

    const lockfile = parseLockfile(input);
    const block = expectFirstBlock(lockfile);
    expect(block.fields.peerDependenciesMeta).toEqual({
      kind: "nested-map",
      entries: { react: { optional: "true" } },
    });
    expect(block.fields.linkType).toBeUndefined();
  });

  it("does not misidentify 5-space lines as nested-map headers", () => {
    const input = [
      '"pkg@npm:1":',
      "  section:",
      "     five-space-key: value",
      "    normal-key: value",
      "",
    ].join("\n");

    const lockfile = parseLockfile(input);
    const block = expectFirstBlock(lockfile);
    // 5-space line is NOT a nested-map header → section is parsed as flat map
    expect(block.fields.section).toEqual({
      kind: "map",
      entries: { " five-space-key": "value", "normal-key": "value" },
    });
  });

  it("skips map entries with empty key (colon at indent boundary)", () => {
    const input = [
      '"pkg@npm:1":',
      "  dependencies:",
      "    : empty-key-value",
      "    valid: 1.0.0",
      "",
    ].join("\n");

    const lockfile = parseLockfile(input);
    const block = expectFirstBlock(lockfile);
    expect(block.fields.dependencies).toEqual({
      kind: "map",
      entries: { valid: "1.0.0" },
    });
  });

  it("skips nested-map key headers with empty key", () => {
    const input = [
      '"pkg@npm:1":',
      "  peerDependenciesMeta:",
      "    :",
      "      optional: true",
      "    react:",
      "      optional: false",
      "",
    ].join("\n");

    const lockfile = parseLockfile(input);
    const block = expectFirstBlock(lockfile);
    expect(block.fields.peerDependenciesMeta).toEqual({
      kind: "nested-map",
      entries: { react: { optional: "false" } },
    });
  });

  it("skips nested-map properties with empty prop name", () => {
    const input = [
      '"pkg@npm:1":',
      "  peerDependenciesMeta:",
      "    react:",
      "      : empty-prop-value",
      "      optional: true",
      "",
    ].join("\n");

    const lockfile = parseLockfile(input);
    const block = expectFirstBlock(lockfile);
    expect(block.fields.peerDependenciesMeta).toEqual({
      kind: "nested-map",
      entries: { react: { optional: "true" } },
    });
  });

  it("produces empty map when all entries are malformed", () => {
    const input = [
      '"pkg@npm:1":',
      "  dependencies:",
      "    no-colon-here",
      "    also-no-colon",
      "  linkType: hard",
      "",
    ].join("\n");

    const lockfile = parseLockfile(input);
    const block = expectFirstBlock(lockfile);
    expect(block.fields.dependencies).toEqual({
      kind: "map",
      entries: {},
    });
  });

  it("produces empty nested-map when all keys are malformed", () => {
    const input = [
      '"pkg@npm:1":',
      "  peerDependenciesMeta:",
      "    not-a-key-header 1.0.0",
      "      orphan: true",
      "  linkType: hard",
      "",
    ].join("\n");

    const lockfile = parseLockfile(input);
    const block = expectFirstBlock(lockfile);
    expect(block.fields.peerDependenciesMeta).toEqual({
      kind: "nested-map",
      entries: {},
    });
  });

  it("serializes lockfile with empty preamble", () => {
    const lockfile: Lockfile = {
      preamble: "",
      blocks: [
        {
          descriptors: ["pkg@npm:1"],
          fields: { version: { kind: "scalar", raw: "1.0.0" } },
        },
      ],
    };
    const output = serializeLockfile(lockfile);
    expect(output).toBe('\n"pkg@npm:1":\n  version: 1.0.0\n');
  });
});

