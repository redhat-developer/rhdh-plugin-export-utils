describe("mutation", () => {
  it("allows updating a scalar value while preserving order", () => {
    const input = [
      "__metadata:",
      "  version: 8",
      "",
      '"pkg@npm:^1.0.0":',
      "  version: 1.0.0",
      '  resolution: "pkg@npm:1.0.0"',
      "  checksum: abc",
      "  linkType: hard",
      "",
    ].join("\n");

    const lockfile = parseLockfile(input);
    const block = expectFirstBlock(lockfile);
    block.fields.version = { kind: "scalar", raw: "2.0.0" };

    expect(roundTrip(lockfile)).toBe(input.replace("version: 1.0.0", "version: 2.0.0"));
  });

  it("allows replacing a dependency value in a map", () => {
    const input = [
      "__metadata:",
      "  version: 8",
      "",
      '"pkg@npm:^1.0.0":',
      "  version: 1.0.0",
      "  dependencies:",
      '    react: "npm:^17.0.0"',
      '    lodash: "npm:^4.0.0"',
      "  linkType: hard",
      "",
    ].join("\n");

    const lockfile = parseLockfile(input);
    const block = expectFirstBlock(lockfile);
    const deps = block.fields.dependencies;
    if (deps?.kind === "map") {
      deps.entries.react = '"npm:^18.0.0"';
    }

    const output = roundTrip(lockfile);
    expect(output).toContain('react: "npm:^18.0.0"');
    expect(output).toContain('lodash: "npm:^4.0.0"');
    expect(output.indexOf("react")).toBeLessThan(output.indexOf("lodash"));
  });

  it("allows adding a new block", () => {
    const input = [
      "__metadata:",
      "  version: 8",
      "",
      '"pkg-a@npm:^1.0.0":',
      "  version: 1.0.0",
      "",
    ].join("\n");

    const lockfile = parseLockfile(input);
    lockfile.blocks.push({
      descriptors: ["pkg-b@npm:^2.0.0"],
      fields: {
        version: { kind: "scalar", raw: "2.0.0" },
        linkType: { kind: "scalar", raw: "hard" },
      },
    });

    const output = roundTrip(lockfile);
    expect(output).toContain('"pkg-b@npm:^2.0.0":');
    expect(output).toContain("version: 2.0.0");
  });

  it("allows removing a block", () => {
    const input = [
      "__metadata:",
      "  version: 8",
      "",
      '"pkg-a@npm:^1.0.0":',
      "  version: 1.0.0",
      "",
      '"pkg-b@npm:^2.0.0":',
      "  version: 2.0.0",
      "",
    ].join("\n");

    const lockfile = parseLockfile(input);
    lockfile.blocks = lockfile.blocks.filter((b) => {
      const firstDescriptor = b.descriptors[0];
      return firstDescriptor === undefined || !firstDescriptor.includes("pkg-b");
    });

    const output = roundTrip(lockfile);
    expect(output).toContain("pkg-a");
    expect(output).not.toContain("pkg-b");
  });

  it("allows enriching descriptors (adding a specifier)", () => {
    const input = [
      "__metadata:",
      "  version: 8",
      "",
      '"@backstage/core@backstage:^":',
      "  version: 1.0.0",
      "",
    ].join("\n");

    const lockfile = parseLockfile(input);
    const block = expectFirstBlock(lockfile);
    block.descriptors.push("@backstage/core@npm:1.0.0");

    const output = roundTrip(lockfile);
    expect(output).toContain('"@backstage/core@backstage:^, @backstage/core@npm:1.0.0":');
  });
});

