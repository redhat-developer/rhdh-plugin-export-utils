describe("getScalar", () => {
  it("returns unquoted value", () => {
    const block: LockfileBlock = {
      descriptors: ["pkg@npm:1"],
      fields: {
        version: { kind: "scalar", raw: "1.0.0" },
        resolution: { kind: "scalar", raw: '"pkg@npm:1.0.0"' },
      },
    };
    expect(getScalar(block, "version")).toBe("1.0.0");
    expect(getScalar(block, "resolution")).toBe("pkg@npm:1.0.0");
  });

  it("returns undefined for missing or non-scalar field", () => {
    const block: LockfileBlock = {
      descriptors: ["pkg@npm:1"],
      fields: {
        deps: { kind: "map", entries: { a: "1" } },
      },
    };
    expect(getScalar(block, "missing")).toBeUndefined();
    expect(getScalar(block, "deps")).toBeUndefined();
  });
});

